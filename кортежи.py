# Напишите программу, которая фильтрует список кортежей, оставляя только те, где количество больше 10.
# Выведите данные согласно примеру.
#
# Данные:
# data = [("апельсин", 5), ("вишня", 12), ("киви", 18), ("ананас", 7), ("яблоко", 20)]
