# Отфильтрованные данные:
# Товар : вишня     	|   Цена : 12
# Товар : киви      	|   Цена : 18
# Товар : яблоко    	|   Цена : 20

data = [("апельсин", 5), ("вишня", 12), ("киви", 18), ("ананас", 7), ("яблоко", 20)]

print("Отфильтрованные данные:")

for item, quantity in data:
    if quantity > 10:
        print(f"Товар : {item:<10} |   Цена : {quantity:>2}")
